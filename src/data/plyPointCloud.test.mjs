// src/data/plyPointCloud.test.mjs
// The browser has to read exactly what ABot-Recon's exporter writes: a
// binary_little_endian vertex block followed by an `edge` element (frustums +
// trajectory) that is NOT point data. Mis-reading the second element would
// scatter thousands of fake points through the scene, so the fixture below is
// byte-shaped like write_binary_ply()'s output, edges included.
import test from 'node:test';
import assert from 'node:assert/strict';
import { decimationStride, parseBinaryPly, parsePlyHeader } from './plyPointCloud.js';

const HEADER = (vertices, edges) => 'ply\n'
  + 'format binary_little_endian 1.0\n'
  + 'comment Generated by ABot-Recon export_reconstruction_ply.py\n'
  + `element vertex ${vertices}\n`
  + 'property float x\nproperty float y\nproperty float z\n'
  + 'property uchar red\nproperty uchar green\nproperty uchar blue\n'
  + `element edge ${edges}\n`
  + 'property int vertex1\nproperty int vertex2\n'
  + 'property uchar red\nproperty uchar green\nproperty uchar blue\n'
  + 'end_header\n';

/**
 * @param {Array<[number, number, number, number, number, number]>} vertices
 * @param {Array<[number, number]>} [edges]
 * @returns {Uint8Array}
 */
function buildPly(vertices, edges = []) {
  const header = new TextEncoder().encode(HEADER(vertices.length, edges.length));
  const bytes = new Uint8Array(header.length + vertices.length * 15 + edges.length * 11);
  bytes.set(header, 0);
  const view = new DataView(bytes.buffer);
  let at = header.length;
  for (const [x, y, z, r, g, b] of vertices) {
    view.setFloat32(at, x, true);
    view.setFloat32(at + 4, y, true);
    view.setFloat32(at + 8, z, true);
    bytes[at + 12] = r;
    bytes[at + 13] = g;
    bytes[at + 14] = b;
    at += 15;
  }
  for (const [v1, v2] of edges) {
    view.setInt32(at, v1, true);
    view.setInt32(at + 4, v2, true);
    bytes[at + 8] = 255;
    bytes[at + 9] = 255;
    bytes[at + 10] = 255;
    at += 11;
  }
  return bytes;
}

test('the exporter format round-trips into interleaved xyz + rgb', () => {
  const cloud = parseBinaryPly(buildPly([
    [1, 2, 3, 10, 20, 30],
    [-4.5, 0, 6.25, 200, 100, 50],
  ], [[0, 1]]));
  assert.equal(cloud.count, 2);
  assert.equal(cloud.totalVertices, 2);
  assert.deepEqual([...cloud.positions], [1, 2, 3, -4.5, 0, 6.25]);
  assert.deepEqual([...cloud.colors], [10, 20, 30, 200, 100, 50]);
});

test('the edge element is skipped, not read as points', () => {
  // Two vertices and 400 trailing edges: a reader that walked past the vertex
  // block would report far more than two points.
  const edges = Array.from({ length: 400 }, (_unused, i) => [i % 2, (i + 1) % 2]);
  const cloud = parseBinaryPly(buildPly([[0, 0, 0, 1, 2, 3], [1, 1, 1, 4, 5, 6]], edges));
  assert.equal(cloud.count, 2);
});

test('header parsing exposes per-element strides in declaration order', () => {
  const { elements } = parsePlyHeader(buildPly([[0, 0, 0, 0, 0, 0]]));
  assert.deepEqual(elements.map((element) => [element.name, element.count, element.stride]), [
    ['vertex', 1, 15],
    ['edge', 0, 11],
  ]);
});

test('non-finite points are dropped rather than poisoning a bounding volume', () => {
  const cloud = parseBinaryPly(buildPly([
    [Number.NaN, 0, 0, 1, 1, 1],
    [7, 8, 9, 2, 2, 2],
    [Number.POSITIVE_INFINITY, 0, 0, 3, 3, 3],
  ]));
  assert.equal(cloud.count, 1);
  assert.deepEqual([...cloud.positions], [7, 8, 9]);
  assert.deepEqual([...cloud.colors], [2, 2, 2]);
});

test('a colorless cloud parses, leaving the palette to the caller', () => {
  const header = new TextEncoder().encode('ply\nformat binary_little_endian 1.0\n'
    + 'element vertex 1\nproperty float x\nproperty float y\nproperty float z\nend_header\n');
  const bytes = new Uint8Array(header.length + 12);
  bytes.set(header, 0);
  new DataView(bytes.buffer).setFloat32(header.length, 5, true);
  const cloud = parseBinaryPly(bytes);
  assert.equal(cloud.count, 1);
  assert.equal(cloud.colors, null);
});

test('decimation honors both the stride and the primitive budget', () => {
  assert.equal(decimationStride(1000, 1, 0), 1);
  assert.equal(decimationStride(1000, 4, 0), 4);
  // 1000 points at stride 4 keeps 250 — already under a 400 cap.
  assert.equal(decimationStride(1000, 4, 400), 4);
  // A 100-point cap needs stride 10, not the requested 4.
  assert.equal(decimationStride(1000, 4, 100), 10);
  assert.equal(decimationStride(0, 1, 100), 1);
});

test('a budgeted load keeps a strided sample of the file', () => {
  const vertices = Array.from({ length: 8 }, (_unused, i) => [i, 0, 0, i, i, i]);
  const cloud = parseBinaryPly(buildPly(vertices), { maxPoints: 4 });
  assert.equal(cloud.stride, 2);
  assert.equal(cloud.count, 4);
  assert.equal(cloud.totalVertices, 8);
  assert.deepEqual([...cloud.positions].filter((_unused, i) => i % 3 === 0), [0, 2, 4, 6]);
});

test('formats and shapes this reader cannot honestly handle are refused', () => {
  const ascii = new TextEncoder().encode('ply\nformat ascii 1.0\nelement vertex 1\n'
    + 'property float x\nend_header\n');
  assert.throws(() => parseBinaryPly(ascii), /unsupported PLY format: ascii/);

  const noEnd = new TextEncoder().encode('ply\nformat binary_little_endian 1.0\n');
  assert.throws(() => parseBinaryPly(noEnd), /missing end_header/);

  const missingZ = new TextEncoder().encode('ply\nformat binary_little_endian 1.0\n'
    + 'element vertex 1\nproperty float x\nproperty float y\nend_header\n');
  assert.throws(() => parseBinaryPly(missingZ), /missing z/);

  // A list property makes the element stride per-record, so the vertices
  // behind it cannot be addressed: refuse instead of mis-reading.
  const faceList = new TextEncoder().encode('ply\nformat binary_little_endian 1.0\n'
    + 'element vertex 1\nproperty float x\nproperty float y\nproperty float z\n'
    + 'element face 1\nproperty list uchar int vertex_indices\nend_header\n');
  assert.throws(() => parseBinaryPly(faceList), /unsupported PLY list property/);

  const truncated = buildPly([[1, 2, 3, 0, 0, 0]]).subarray(0, -4);
  assert.throws(() => parseBinaryPly(truncated), /truncated/);
});
